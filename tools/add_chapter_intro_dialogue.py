def main() -> int:
    src = open(PATH, encoding="utf-8").read()
    if MARKER not in src:
        # 마커가 없으면 이미 삽입됐는지 확인
        if "chapterIntro_forest" in src:
            print("이미 삽입됨 — 변경 없음")
            return 0
        print("마커를 찾지 못함 — 중단")
        return 2

    blocks = []
    for key, (speaker, lines) in LINES.items():
        body = "\n".join(f'      "{l}",' for l in lines)
        blocks.append(
            f'  chapterIntro_{key}: {{\n'
            f'    speaker: "{speaker}",\n'
            f'    lines: [\n{body}\n    ],\n'
            f'  }},'
        )

    payload = (
        "  /* v1.4.41 — 챕터 진입 컷씬 대사 19종.\n"
        "   *  StoryCutscene 이 카메라 연출을 재생할 때 이 키로 대사를 띄운다.\n"
        "   *  화자는 챕터별 안내자(대부분 이그니 계열) — 세계관: 라일락 · 다섯 왕국 · 인피니트보석. */\n"
        + "\n".join(blocks)
    )

    out = src.replace(MARKER, payload, 1)
    open(PATH, "w", encoding="utf-8").write(out)
    print(f"삽입 완료 — {len(LINES)}개 챕터 대사")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
