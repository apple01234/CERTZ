/** 레벨 lv → lv+1 에 필요한 경험치 (테이블 원본값) */
export function expToNext(lv: number): number {
  const i = Math.max(1, Math.floor(lv));
  if (i <= EXP_TABLE_MAX) return EXP_TABLE[i];
  /* 만렙(300) 이후 연장: 마지막 값에서 레벨당 ×1.1 */
  let v = EXP_TABLE[EXP_TABLE_MAX];
  for (let k = EXP_TABLE_MAX + 1; k <= i; k++) v = Math.round(v * 1.1);
  return v;
}
