/**
 * 스테이지별 대사 — "걷는 대사" 3개 순환을 없애기 위한 데이터 계층
 *
 * 왜 뽑았나
 *   종전 `stageIntro()` 는 서브 2~9 를 전부 `ch{num}Walk{((sub-2)%3)+1}` 로 보냈다.
 *   슬롯이 3개뿐이라 7개 구역이 같은 대사를 세 번씩 돌려썼고, 챕터를 진행해도
 *   "또 그 얘기"가 나왔다. 반대로 아이템 200개에 태그를 심는 식으로 풀면
 *   데이터만 불어나고 서사는 그대로다.
 *
 * 무엇
 *   · CHAPTER_POOL   — 챕터당 공통 풀 6줄. 그 챕터의 지형·분위기·목표만 말한다.
 *   · STAGE_BEATS    — (챕터, 구역)별 고유 비트 1~2줄. 그 구역에서만 나오는 사건.
 *   · stageDialogueLines(ch, sub) — 구역마다 **서로 다른 조합**을 결정론적으로 고른다.
 *
 * 순환을 없애는 방법
 *   풀 6줄에서 시작 오프셋을 구역마다 다르게 잡고(`(sub-2)`), 거기에 고유 비트를
 *   앞에 붙인다. 서브 2~9 는 8개 구역이고 풀이 6줄이므로 **시작 위치만으로도**
 *   이웃 구역이 같은 줄로 시작하지 않는다. 고유 비트가 있으면 조합 자체가 달라진다.
 *   구역당 3줄(비트 1 + 풀 2)이고, 8구역 합계 24줄 중 풀 중복은 6줄뿐이다.
 *
 * 이 파일이 지켜야 하는 계약
 *   · Phaser / DOM / Math.random 의존 없음. 같은 (ch, sub) 면 언제나 같은 결과.
 *   · 서사 금지어(옛 캠페인 표기)를 쓰지 않는다 — `retired-story-removal.test.mjs` 가
 *     DIALOGUES 전체를 직렬화해 검사한다.
 *   · 챕터풀이 없는 키(재림·영프·마을)는 빈 배열을 돌려준다 → 호출부가 기존 키로 폴백.
 *   · 완전히 새로운 밸런스/시스템을 만들지 않는다. 문구만 공급한다.
 */

