/**
 * 구역별 걷는 대사 3줄. 고유 비트(있으면) + 같은 챕터 풀에서 오프셋을 달리한 2줄.
 *
 * 왜 3줄인가: 종전 Walk 대사가 1줄이었는데, 3줄로 늘리면 대사창 한 번에 그 구역의
 * 맥락이 잡힌다. 8구역 × 3줄 = 24줄이지만 풀 재사용 덕에 서로 다른 시작점을 갖는다.
 * 결정론: 같은 (ch, sub) 면 항상 같은 배열. 호출부가 매번 같은 대사를 본다.
 */
export function stageDialogueLines(ch: string, sub: number): string[] {
  const pool = CHAPTER_POOL[ch];
  if (!pool || !pool.length) return [];
  const out: string[] = [];
  const beat = STAGE_BEATS[ch]?.[sub];
  if (beat?.length) out.push(beat[0]);
  /* 오프셋: 구역마다 다른 줄에서 시작한다. sub=2 → 0, 3 → 1 …
   * 유한 루프 — 풀이 3줄 미만이면 있는 만큼만 돌려준다(무한 루프 방지).
   * 데이터가 늘어도 이 함수는 pool.length 번만 돈다. */
  const start = (((sub - 2) % pool.length) + pool.length) % pool.length;
  for (let i = 0; i < pool.length && out.length < 3; i++) {
    const line = pool[(start + i) % pool.length];
    if (!out.includes(line)) out.push(line);
  }
  return out;
}

/** 이 챕터가 확장 대사 풀을 갖는지 (없으면 호출부가 기존 키로 폴백). */
export function hasStageDialogue(ch: string): boolean {
  return !!CHAPTER_POOL[ch];
}
