function build(rows: typeof ACT_ONE, act: 1 | 2 | 3): ChapterDefinition[] {
  return rows.map(
    (
      [
        title,
        location,
        guide,
        opening,
        kind,
        targets,
        resolution,
        memory,
        theme,
        boss,
      ],
      index,
    ) => {
      const id = `a${act}-${String(index + 1).padStart(2, "0")}`;
      const objectives: ObjectiveDefinition[] = [
        {
          id: `${id}:arrival`,
          kind: "talk",
          title: `${guide}에게 이야기 듣기`,
          targets: [guide],
          hint: "빛나는 인물에게 다가가 E / 대화",
          lines: [
            { speaker: guide, text: opening },
            {
              speaker: "연합 기록관",
              text: "당신은 연합의 동행자입니다. 영웅들이 싸우는 동안, 사람과 사람을 잇는 일을 맡습니다.",
            },
          ],
        },
        {
          id: `${id}:field`,
          kind,
          title:
            kind === "puzzle"
              ? "원소의 흐름을 순서대로 연결하기"
              : kind === "defend"
                ? "전선을 지키며 세 지점 확보하기"
                : kind === "talk"
                  ? "서로의 이야기를 듣고 약속 잇기"
                  : "현장에서 단서 모으기",
          targets,
          hint:
            kind === "puzzle"
              ? `${targets.join(" → ")} 순서로 작동하세요.`
              : kind === "defend"
                ? "습격을 피하고 장치를 하나씩 확보하세요."
                : "금빛 표식을 찾아 가까이에서 상호작용하세요.",
        },
      ];
      if (boss)
        objectives.push({
          id: `${id}:boss`,
          kind: "boss",
          title: `${boss} 돌파`,
          targets: [boss],
          hint: "붉은 공격 예고를 피하고, 공격이 끝난 뒤 드러나는 빈틈을 노리세요.",
        });
      objectives.push({
        id: `${id}:farewell`,
        kind: "talk",
        title: "동료와 사건 정리하기",
        targets: [guide],
        hint: "동료에게 돌아가 대화하면 다음 장이 열립니다.",
        lines: [{ speaker: guide, text: resolution }],
      });
      return {
        id,
        act,
        episode: index + 1,
        title,
        location,
        theme,
        guide,
        summary: opening,
        objectives,
        ending: [{ speaker: guide, text: resolution }],
        memory,
        source:
          act === 1 ? "manuscript" : act === 2 ? "sequel-notes" : "adaptation",
        ...(boss
          ? {
              boss: {
                name: boss,
                pattern: (["tide", "cross", "ring", "storm"] as const)[
                  index % 4
                ],
                color: act === 1 ? 0xc8678e : act === 2 ? 0x839de8 : 0xd7a95a,
              },
            }
          : {}),
      };
    },
  );
}
